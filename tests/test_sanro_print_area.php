<?php
define('ABSPATH', __DIR__ . '/');
require __DIR__ . '/../plugins/sanro-studio/includes/print-area.php';
$checks = 0;
function check_area($expected, $actual, $label) {
    global $checks;
    if ($expected !== $actual) throw new RuntimeException('FAIL: ' . $label . ' expected ' . var_export($expected, true) . ', got ' . var_export($actual, true));
    $checks++;
}
$area = ['width' => 40, 'height' => 50];
$img = ['type' => 'image', 'x' => 0, 'y' => 0, 'width' => 10, 'height' => 10];
$text = ['type' => 'text', 'x' => 12, 'y' => 15, 'width' => 8, 'height' => 5];
check_area(true, sanro_studio_validate_print_side([$img], $area)['valid'], 'single image');
check_area('A4', sanro_studio_validate_print_side([$img, $text], $area)['category'], 'combined span requires A4');
check_area(true, sanro_studio_validate_print_side([$img, $text], $area)['valid'], 'combined span fits A4');
check_area('too_many_objects', sanro_studio_validate_print_side([$img, $text, $img], $area)['error'], 'too many');
check_area('invalid_object_type', sanro_studio_validate_print_side([$img, $img], $area)['error'], 'duplicate image');
check_area('outside_safe_area', sanro_studio_validate_print_side([array_merge($img, ['x' => 35])], $area)['error'], 'safe area');
check_area('invalid_geometry', sanro_studio_validate_print_side([array_merge($img, ['width' => INF])], $area)['error'], 'infinite dimension');
check_area('invalid_geometry', sanro_studio_validate_print_side([array_merge($img, ['width' => 'NaN'])], $area)['error'], 'nan dimension');
check_area('outside_safe_area', sanro_studio_validate_print_side([array_merge($img, ['x' => -1])], $area)['error'], 'negative position');
check_area(true, sanro_studio_validate_print_side([], $area)['empty'], 'empty side');
check_area('invalid_safe_area', sanro_studio_validate_print_side([$img], ['width' => 0, 'height' => 10])['error'], 'invalid safe area');
check_area('category_exceeded', sanro_studio_validate_print_side([array_merge($img, ['width' => 33])], $area)['error'], 'reject footprint larger than A3+');
$front = ['objects' => [$img], 'category' => 'A5'];
$back = ['objects' => [$text], 'category' => 'A4'];
$areas = ['front' => $area, 'back' => $area];
check_area(true, sanro_studio_validate_print_design(['front' => $front, 'back' => $back], $areas)['valid'], 'both sides valid');
check_area(true, sanro_studio_validate_print_design(['back' => $back], $areas)['valid'], 'back only valid');
check_area(true, sanro_studio_validate_print_design(['front' => $front], $areas)['valid'], 'front only valid');
check_area('empty_design', sanro_studio_validate_print_design([], $areas)['error'], 'no printable side rejected');
check_area('empty_design', sanro_studio_validate_print_design(['front' => ['objects' => [], 'category' => 'A5']], $areas)['error'], 'empty front rejected');
check_area('invalid_design', sanro_studio_validate_print_design(['left' => $front], $areas)['error'], 'unknown side rejected');
check_area('A5', sanro_studio_validate_print_design(['front' => ['objects' => [$img]]], $areas)['sides']['front']['category'], 'category computed without buyer input');
check_area('invalid_design', sanro_studio_validate_print_design(['front' => $front], [])['error'], 'missing admin safe area rejected');
check_area('invalid_design', sanro_studio_validate_print_design(['front' => $front + ['price' => 1]], $areas)['error'], 'browser price rejected');
check_area('invalid_objects', sanro_studio_validate_print_side(['image' => $img], $area)['error'], 'associative object map rejected');
check_area('invalid_objects', sanro_studio_validate_print_side([1 => $img], $area)['error'], 'sparse object list rejected');
check_area('invalid_object_type', sanro_studio_validate_print_side([array_merge($img, ['price' => 1])], $area)['error'], 'untrusted object price rejected');
check_area('invalid_object_type', sanro_studio_validate_print_side([array_merge($img, ['safe_area' => $area])], $area)['error'], 'untrusted safe area field rejected');
$rotated = ['type'=>'image','x'=>2,'y'=>12,'width'=>18,'height'=>6,'rotation'=>90];
check_area('A5',sanro_studio_validate_print_side([$rotated],$area)['category'],'quarter turn changes physical width');
$rotated['rotation'] = 45;
check_area('A4',sanro_studio_validate_print_side([$rotated],$area)['category'],'diagonal expands axis-aligned footprint');
$rotated['x'] = 35;
check_area('outside_safe_area',sanro_studio_validate_print_side([$rotated],$area)['error'],'rotated corners outside printable region');
$rotated['rotation'] = INF;
check_area('invalid_geometry',sanro_studio_validate_print_side([$rotated],$area)['error'],'non-finite angles rejected');
check_area(null,sanro_studio_validate_print_side([],$area)['category'],'blank side has no tier');
$legacy = sanro_studio_validate_print_design(['front'=>['objects'=>[$img,$text],'category'=>'A5'],'back'=>$back],$areas);
check_area('A4',$legacy['sides']['front']['category'],'under-accounted legacy tier ignored');
check_area('A5',$legacy['sides']['back']['category'],'other side measured independently');
echo "SANRO print bounds: {$checks} assertions PASS, 0 FAIL\n";
